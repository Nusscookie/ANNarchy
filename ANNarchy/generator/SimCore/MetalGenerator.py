import os
import re

from ANNarchy.intern.ConfigManagement import ConfigManager
from ANNarchy.intern.NetworkManager import NetworkManager
from ANNarchy.intern import Messages

from ANNarchy.generator.Template import CUDABaseTemplate
from ANNarchy.generator.SimCore.CUDAGenerator import CUDAGenerator
from ANNarchy.generator.Metal import MetalTemplates
from ANNarchy.generator.Metal.Translator import (
    translate,
    to_cpp_raw_string,
    MetalTranslationError,
)


class MetalGenerator(CUDAGenerator):
    """
    Simulation core for the Metal paradigm.

    The code is generated by the CUDA generator. Afterwards, the device code
    (ANNarchyKernel[net_id].cu) is translated into a Metal shader library
    (ANNarchyKernels[net_id].metal) and the kernel invocations into C++ code
    (ANNarchyKernel[net_id].cpp). The host code uses the CUDA compatibility
    layer (include/metal/cuda_compat.hpp).
    """

    def generate_header(self, source_dest, pop_desc, proj_desc):
        super().generate_header(source_dest, pop_desc, proj_desc)

        # Replace the CUDA headers by the compatibility layer
        for fname in [
            "ANNarchyKernel" + str(self._net_id) + ".cuh",
            "ANNarchyCore" + str(self._net_id) + ".hpp",
        ]:
            path = source_dest + fname
            with open(path, "r", encoding="utf-8") as rfile:
                code = rfile.read()
            code = code.replace("#include <cuda_runtime_api.h>\n", MetalTemplates.compat_include)
            code = code.replace("#include <curand_kernel.h>\n", "")
            code = re.sub(
                r"inline void setDevice\(const int device_id\) \{.*?\n\}",
                lambda m: MetalTemplates.set_device,
                code,
                flags=re.DOTALL,
            )
            with open(path, "w", encoding="utf-8") as wfile:
                wfile.write(code)

    def generate_body(self, annarchy_dir, source_dest, prof_gen, pop_gen, pop_desc, proj_desc):
        # Generate the CUDA code with section markers in the device code, the
        # monitors are finalized at the end of run() and step()
        original_device = CUDABaseTemplate.device_kernel
        original_host = CUDABaseTemplate.host_body_template
        CUDABaseTemplate.device_kernel = MetalTemplates.marked_device_kernel
        CUDABaseTemplate.host_body_template = original_host.replace(
            MetalTemplates.host_sync, MetalTemplates.host_sync_and_finalize
        )
        try:
            super().generate_body(annarchy_dir, source_dest, prof_gen, pop_gen, pop_desc, proj_desc)
        finally:
            CUDABaseTemplate.device_kernel = original_device
            CUDABaseTemplate.host_body_template = original_host

        cu_file = source_dest + "ANNarchyKernel" + str(self._net_id) + ".cu"
        with open(cu_file, "r", encoding="utf-8") as rfile:
            sections = self._split_sections(rfile.read())
        os.remove(cu_file)

        # Global constants are implemented by the translator (the CUDA code in
        # sections["custom_constant"] is not used)
        float_prec = ConfigManager().get("precision", self._net_id)
        constants = [
            (obj.name, float_prec)
            for obj in NetworkManager().get_network(self._net_id).get_constants()
        ]

        device_code = "\n".join(sections[key] for key in MetalTemplates.device_sections)
        host_code = "\n".join(sections[key] for key in MetalTemplates.host_sections)

        try:
            msl_code, launchers, host_code = translate(device_code, host_code, constants)
        except MetalTranslationError as e:
            Messages.error("Metal code generation failed:", str(e))

        shader = MetalTemplates.msl_prelude % {"float_prec": float_prec} + msl_code

        with open(source_dest + "ANNarchyKernels" + str(self._net_id) + ".metal", "w", encoding="utf-8") as wfile:
            wfile.write(shader)

        host = MetalTemplates.host_base % {
            "net_id": self._net_id,
            "float_prec": float_prec,
            "shader_source": to_cpp_raw_string("annmtl_shader_source", shader),
            "launchers": launchers,
            "invocations": host_code,
        }
        with open(source_dest + "ANNarchyKernel" + str(self._net_id) + ".cpp", "w", encoding="utf-8") as wfile:
            wfile.write(host)

        # Sanity check: kernels must not be launched from other host files
        core_file = source_dest + "ANNarchyCore" + str(self._net_id) + ".cpp"
        with open(core_file, "r", encoding="utf-8") as rfile:
            if "<<<" in rfile.read():
                Messages.error("Metal code generation failed: kernel launch in", core_file)

    @staticmethod
    def _split_sections(code):
        sections = {}
        parts = re.split(r"^//@@ANNMTL (\w+)\n", code, flags=re.MULTILINE)
        # parts = [prefix, name1, content1, name2, content2, ...]
        for i in range(1, len(parts) - 1, 2):
            sections[parts[i]] = parts[i + 1]
        return sections
