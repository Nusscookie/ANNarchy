"""
:copyright: Copyright 2013 - now, see AUTHORS.
:license: GPLv2, see LICENSE for details.

Translation of the CUDA code generated by ANNarchy into the Metal Shading
Language (MSL) and the corresponding host code.

The CUDA code generators produce device code (``__global__`` kernels and
``__device__`` functions) and host code which launches the kernels with the
``kernel<<<blocks, threads, shared_mem, stream>>>(args)`` syntax. The
translation is purely syntactical:

* each kernel becomes an MSL kernel. Pointer arguments are bound as device
  buffers, all scalar arguments are packed into one structure (so that the
  number of buffer slots is not exceeded), the CUDA built-in variables
  (threadIdx, blockIdx, blockDim, gridDim) are passed as kernel attributes.
  Shared memory becomes threadgroup memory, __syncthreads() a threadgroup
  barrier and warp-synchronous reductions are replaced by SIMD-group functions.

* each kernel launch in the host code is replaced by a call to a generated
  launcher function, which binds the arguments and dispatches the kernel
  through the Metal runtime (include/metal/MetalRuntime.h).
"""

import re

from ANNarchy.intern import Messages


class MetalTranslationError(Exception):
    pass


# MSL built-in variables replacing the CUDA ones
_builtin_params = [
    "uint3 threadIdx [[thread_position_in_threadgroup]]",
    "uint3 blockIdx [[threadgroup_position_in_grid]]",
    "uint3 blockDim [[threads_per_threadgroup]]",
    "uint3 gridDim [[threadgroups_per_grid]]",
]

# Scalar types which are named differently in MSL
_msl_types = {
    "long int": "long",
    "long long": "long",
    "long long int": "long",
    "signed long": "long",
    "unsigned long": "ulong",
    "unsigned long int": "ulong",
    "unsigned long long": "ulong",
    "unsigned long long int": "ulong",
    "unsigned int": "uint",
    "unsigned": "uint",
    "unsigned short": "ushort",
    "unsigned char": "uchar",
    "size_t": "ulong",
    "double": "float",
}


#####################################################################
#   Helpers                                                         #
#####################################################################
def strip_comments(code):
    """
    Remove C/C++ comments, string and character literals are kept.
    """
    result = []
    i = 0
    n = len(code)
    while i < n:
        c = code[i]
        if c == "/" and i + 1 < n and code[i + 1] == "/":
            j = code.find("\n", i)
            if j < 0:
                break
            i = j
        elif c == "/" and i + 1 < n and code[i + 1] == "*":
            j = code.find("*/", i + 2)
            if j < 0:
                break
            # keep line breaks to preserve the layout
            result.append("\n" * code.count("\n", i, j))
            i = j + 2
        elif c in "\"'":
            j = i + 1
            while j < n and code[j] != c:
                if code[j] == "\\":
                    j += 1
                j += 1
            result.append(code[i : j + 1])
            i = j + 1
        else:
            result.append(c)
            i += 1
    return "".join(result)


def find_matching(code, start, open_char, close_char):
    """
    Returns the index of the bracket closing the one at position start.
    """
    depth = 0
    for i in range(start, len(code)):
        if code[i] == open_char:
            depth += 1
        elif code[i] == close_char:
            depth -= 1
            if depth == 0:
                return i
    raise MetalTranslationError(f"unbalanced '{open_char}' in generated code")


def split_top_level(text, sep=","):
    """
    Split at the separator, ignoring separators enclosed in brackets.
    """
    parts = []
    depth = 0
    current = []
    for c in text:
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == sep and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(c)
    parts.append("".join(current))
    return [p.strip() for p in parts if p.strip() != ""]


def normalize_type(ctype):
    return " ".join(ctype.replace("__restrict__", " ").split())


def msl_type(ctype):
    """
    MSL equivalent of a C scalar type.
    """
    ctype = normalize_type(ctype)
    return _msl_types.get(ctype, ctype)


def host_field_type(ctype):
    """
    Type of a scalar argument in the argument structure on the host side. The
    layout must be identical to the MSL structure, i.e. double is passed as float.
    """
    ctype = normalize_type(ctype)
    return "float" if ctype == "double" else ctype


#####################################################################
#   Kernel parameters                                               #
#####################################################################
_type_words = {"int", "long", "short", "char", "bool", "float", "double", "unsigned", "signed", "size_t", "curandState"}


class KernelParam:
    """
    A parameter of a CUDA kernel.
    """

    def __init__(self, decl, position=0):
        d = normalize_type(decl)

        # unnamed parameters are valid C++, e.g. "const long int, const float dt"
        last = d.replace("*", " * ").split()[-1]
        if last in _type_words or last == "*":
            d = f"{d} annmtl_unnamed_{position}"
            decl = d
        self.decl = " ".join(decl.split())

        if "*" in d:
            base, name = d.rsplit("*", 1)
            self.name = name.strip()
            base = base.strip()
            if "*" in base:
                raise MetalTranslationError(f"pointer to pointer arguments are not supported ({decl})")
            words = base.split()
            self.is_const = "const" in words
            words = [w for w in words if w not in ["const", "volatile"]]
            self.base_type = " ".join(words)
            self.is_pointer = True
        else:
            words = d.split()
            self.name = words[-1]
            words = words[:-1]
            self.is_const = "const" in words
            words = [w for w in words if w not in ["const", "volatile"]]
            self.base_type = " ".join(words)
            self.is_pointer = False

        if not re.match(r"^\w+$", self.name):
            raise MetalTranslationError(f"could not parse kernel argument '{decl}'")

    def msl_buffer_decl(self, index):
        const = "const " if self.is_const else ""
        return f"{const}device {msl_type(self.base_type)}* {self.name} [[buffer({index})]]"

    def msl_field_decl(self):
        return f"{msl_type(self.base_type)} {self.name};"

    def host_field_decl(self):
        return f"{host_field_type(self.base_type)} {self.name};"


class Kernel:
    """
    A CUDA kernel (__global__ function) found in the device code.
    """

    def __init__(self, name, params, body, template_params=None):
        self.name = name
        self.params = params
        self.body = body
        self.template_params = template_params
        self.instantiations = []  # template arguments used by the host code

        self.buffers = [p for p in params if p.is_pointer]
        self.scalars = [p for p in params if not p.is_pointer]

    def args_struct_name(self):
        return f"{self.name}_args"


#####################################################################
#   Device code                                                     #
#####################################################################
_kernel_head = re.compile(r"(template\s*<([^<>]*)>\s*)?__global__\s+void\s+(\w+)\s*\(")


def parse_device_code(code):
    """
    Split the device code into kernels and other code (device functions,
    macros etc.). Returns a list of str and Kernel objects.
    """
    items = []
    pos = 0
    while True:
        m = _kernel_head.search(code, pos)
        if m is None:
            items.append(code[pos:])
            break

        items.append(code[pos : m.start()])

        paren_open = m.end() - 1
        paren_close = find_matching(code, paren_open, "(", ")")
        param_text = strip_comments(code[paren_open + 1 : paren_close])
        params = [KernelParam(p, i) for i, p in enumerate(split_top_level(param_text))]

        brace_open = code.index("{", paren_close)
        brace_close = find_matching(code, brace_open, "{", "}")
        body = code[brace_open + 1 : brace_close]

        template_params = m.group(2).strip() if m.group(1) else None
        items.append(Kernel(m.group(3), params, body, template_params))
        pos = brace_close + 1

    return items


# shared memory declarations
_extern_shared = re.compile(
    r"extern\s+(?:__shared__\s+)?((?:\w+\s+)*?\w+)\s+(?:__shared__\s+)?(\w+)\s*\[\s*\]\s*;"
)
_static_shared = re.compile(
    r"(?:__shared__\s+((?:\w+\s+)*?\w+)|((?:\w+\s+)*?\w+)\s+__shared__)\s+(\w+)\s*((?:\[[^\]]*\]\s*)+);"
)

# local pointer declarations, e.g. "const int *coord = &pre_coords[4*bIdx];"
_local_pointer = re.compile(
    r"(^|[;{}(])(\s*)(?:(?:const|volatile|unsigned|signed|long|short)\s+)*\w+\s*\*\s*(\w+)\s*=(?!=)",
    re.MULTILINE,
)

# One step of a warp-synchronous reduction: a statement accessing [idx + offset]
def _reduction_step(offset, first=False):
    idx = r"(?P<idx>\w+)" if first else r"(?P=idx)"
    name = "s%d" % offset
    return r"(?P<%s>[^;{}]*\[\s*%s\s*\+\s*%d\s*\][^;{}]*;)" % (name, idx, offset)


_warp_reduction = re.compile(
    _reduction_step(16, True)
    + r"\s*"
    + _reduction_step(8)
    + r"\s*"
    + _reduction_step(4)
    + r"\s*"
    + _reduction_step(2)
    + r"\s*"
    + _reduction_step(1)
)


def _replace_warp_reduction(m):
    """
    The CUDA templates reduce data[tid] ... data[tid+31] within one warp
    without synchronization (the first 16 threads execute data[tid] op=
    data[tid+16], data[tid+8], ...). This relies on warp-synchronous
    execution, which is not guaranteed in Metal. The reduction is replaced
    by the SIMD-group functions over the active threads.
    """
    first = m.group("s16")
    idx = m.group("idx")

    arr_match = re.search(r"(\w+)\s*\[\s*%s\s*\]" % idx, first)
    if arr_match is None:
        raise MetalTranslationError("could not translate warp reduction: " + first.strip())
    arr = arr_match.group(1)

    left = f"{arr}[{idx}]"
    right = f"{arr}[{idx} + 16]"
    if "min(" in first:
        op = "min"
    elif "max(" in first:
        op = "max"
    elif re.search(r"\bif\s*\(", first):
        cond = first[first.index("(") + 1 : first.index(")")]
        if ">" in cond:
            op = "min"  # the smaller value is copied
        elif "<" in cond:
            op = "max"
        else:
            raise MetalTranslationError("could not translate warp reduction: " + first.strip())
    elif "+" in first:
        op = "sum"
    else:
        raise MetalTranslationError("could not translate warp reduction: " + first.strip())

    if op == "sum":
        combine = f"{left} + {right}"
    else:
        combine = f"{op}({left}, {right})"

    return (
        f"\n{{ auto annmtl_v = {combine}; annmtl_v = simd_{op}(annmtl_v); if ({idx} == 0) {arr}[0] = annmtl_v; }}\n"
    )


def translate_kernel_body(kernel):
    """
    Translate the body of a CUDA kernel into MSL.
    """
    body = strip_comments(kernel.body)

    # dynamic shared memory becomes a threadgroup buffer argument
    dynamic_shared = None
    for m in _extern_shared.finditer(body):
        if dynamic_shared is not None:
            raise MetalTranslationError(f"kernel {kernel.name}: more than one dynamic shared array")
        dynamic_shared = (normalize_type(m.group(1)), m.group(2))
    body = _extern_shared.sub("", body)

    # static shared memory is declared at kernel scope
    hoisted = []

    def _hoist(m):
        ctype = m.group(1) if m.group(1) else m.group(2)
        hoisted.append(f"threadgroup {msl_type(ctype)} {m.group(3)}{m.group(4).strip()};")
        return ""

    body = _static_shared.sub(_hoist, body)

    if "__shared__" in body:
        raise MetalTranslationError(f"kernel {kernel.name}: unsupported shared memory declaration")

    # synchronization
    body = re.sub(
        r"__syncthreads\s*\(\s*\)",
        "threadgroup_barrier(mem_flags::mem_threadgroup | mem_flags::mem_device)",
        body,
    )

    # warp-synchronous reductions
    body = _warp_reduction.sub(_replace_warp_reduction, body)

    # local pointers: the address space is deduced
    body = _local_pointer.sub(lambda m: f"{m.group(1)}{m.group(2)}auto {m.group(3)} =", body)

    for unsupported in ["__shfl", "__syncwarp", "__ballot", "__any_sync", "__all_sync", "cudaMemcpy"]:
        if unsupported in body:
            raise MetalTranslationError(f"kernel {kernel.name}: '{unsupported}' is not supported")

    return body, hoisted, dynamic_shared


def kernel_signature(kernel, dynamic_shared, constants):
    """
    MSL parameter list of the kernel.
    """
    params = []
    for i, p in enumerate(kernel.buffers):
        params.append(p.msl_buffer_decl(i))
    num_buffers = len(kernel.buffers)
    if len(constants) > 0:
        params.append(f"constant annmtl_constants_t& annmtl_constants [[buffer({num_buffers})]]")
        num_buffers += 1
    if len(kernel.scalars) > 0:
        params.append(f"constant {kernel.args_struct_name()}& annmtl_args [[buffer({num_buffers})]]")
    if dynamic_shared is not None:
        ctype, name = dynamic_shared
        params.append(f"threadgroup {msl_type(ctype)}* {name} [[threadgroup(0)]]")
    params += _builtin_params
    return ",\n    ".join(params)


def translate_kernel(kernel, constants):
    """
    Generate the MSL code of a kernel.
    """
    body, hoisted, dynamic_shared = translate_kernel_body(kernel)

    code = ""

    # structure holding the scalar arguments
    if len(kernel.scalars) > 0:
        fields = "\n".join("    " + p.msl_field_decl() for p in kernel.scalars)
        code += f"struct {kernel.args_struct_name()} {{\n{fields}\n}};\n"

    signature = kernel_signature(kernel, dynamic_shared, constants)

    prologue = ""
    for name, ctype in constants:
        prologue += f"    const {msl_type(ctype)} {name} = annmtl_constants.{name};\n"
    for p in kernel.scalars:
        const = "const " if p.is_const else ""
        prologue += f"    {const}{msl_type(p.base_type)} {p.name} = annmtl_args.{p.name};\n"
    for decl in hoisted:
        prologue += "    " + decl + "\n"

    template = f"template<{kernel.template_params}>\n" if kernel.template_params else ""
    code += f"{template}kernel void {kernel.name}(\n    {signature})\n{{\n{prologue}{body}\n}}\n"

    # explicit instantiations of kernel templates
    for value in kernel.instantiations:
        code += (
            f'template [[host_name("{instance_name(kernel.name, value)}")]] kernel void '
            f"{kernel.name}<{value}>(\n    {signature});\n"
        )

    return code


def instance_name(name, template_value):
    if template_value is None:
        return name
    return name + "_" + re.sub(r"\W+", "_", template_value.strip())


#####################################################################
#   Host code                                                       #
#####################################################################
_launch = re.compile(r"\b(\w+)\s*(?:<\s*([^<>]*?)\s*>)?\s*<<<(.*?)>>>\s*\(", re.DOTALL)


def collect_instantiations(host_code, kernels):
    """
    Template kernels need an explicit instantiation for each launch configuration.
    """
    for m in _launch.finditer(host_code):
        name, value = m.group(1), m.group(2)
        if name in kernels and value is not None:
            if value not in kernels[name].instantiations:
                kernels[name].instantiations.append(value)


def translate_launches(host_code, kernels):
    """
    Replace kernel<<<...>>>(...) by calls to the launcher functions.
    """
    result = []
    pos = 0
    used = set()
    for m in _launch.finditer(host_code):
        if m.start() < pos:
            continue
        name, value, config = m.group(1), m.group(2), m.group(3)
        if name not in kernels:
            raise MetalTranslationError(f"launch of unknown kernel '{name}'")
        kernel = kernels[name]

        paren_open = m.end() - 1
        paren_close = find_matching(host_code, paren_open, "(", ")")
        args = split_top_level(strip_comments(host_code[paren_open + 1 : paren_close]))
        if len(args) != len(kernel.params):
            raise MetalTranslationError(
                f"launch of kernel '{name}' with {len(args)} arguments, expected {len(kernel.params)}"
            )

        cfg = split_top_level(strip_comments(config))
        if len(cfg) < 2:
            raise MetalTranslationError(f"invalid launch configuration for kernel '{name}'")
        nb, tpb = cfg[0], cfg[1]
        smem = cfg[2] if len(cfg) > 2 else "0"

        launcher = "annmtl_launch_" + instance_name(name, value)
        used.add((name, value))

        result.append(host_code[pos : m.start()])
        result.append(f"{launcher}({nb}, {tpb}, {smem}, {', '.join(args)})")
        pos = paren_close + 1

    result.append(host_code[pos:])
    return "".join(result), used


def generate_launcher(kernel, template_value, constants):
    """
    Host function binding the arguments and dispatching the kernel.
    """
    name = instance_name(kernel.name, template_value)
    params = ", ".join(p.decl for p in kernel.params)

    code = f"static void annmtl_launch_{name}(dim3 annmtl_nb, dim3 annmtl_tpb, size_t annmtl_smem, {params}) {{\n"
    code += f'    static int annmtl_pso = annmtl_pipeline("{name}");\n'

    if len(kernel.scalars) > 0:
        fields = " ".join(p.host_field_decl() for p in kernel.scalars)
        code += f"    struct {{ {fields} }} annmtl_args;\n"
        for p in kernel.scalars:
            code += f"    annmtl_args.{p.name} = {p.name};\n"
        args_ptr, args_size = "&annmtl_args", "sizeof(annmtl_args)"
    else:
        args_ptr, args_size = "nullptr", "0"

    buffers = [f"(const void*){p.name}" for p in kernel.buffers]
    if len(constants) > 0:
        buffers.append("(const void*)annmtl_get_constants()")
    if len(buffers) > 0:
        code += f"    const void* annmtl_buffers[] = {{ {', '.join(buffers)} }};\n"
        buffers_ptr = "annmtl_buffers"
    else:
        buffers_ptr = "nullptr"

    code += (
        f"    annmtl_dispatch(annmtl_pso, annmtl_nb.x, annmtl_nb.y, annmtl_nb.z, annmtl_tpb.x, annmtl_tpb.y, annmtl_tpb.z, "
        f"{buffers_ptr}, {len(buffers)}, {args_ptr}, {args_size}, annmtl_smem);\n"
    )
    code += "}\n"
    return code


