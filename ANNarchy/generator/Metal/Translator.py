def constants_code(constants):
    """
    Global constants are stored in one buffer, which is bound to all kernels.

    Returns: (msl_code, host_code)
    """
    if len(constants) == 0:
        return "", ""

    msl_fields = "\n".join(f"    {msl_type(ctype)} {name};" for name, ctype in constants)
    host_fields = "\n".join(f"    {host_field_type(ctype)} {name};" for name, ctype in constants)

    msl = f"struct annmtl_constants_t {{\n{msl_fields}\n}};\n"
    host = f"""struct annmtl_constants_t {{
{host_fields}
}};
static annmtl_constants_t* annmtl_constants_ptr = nullptr;
static annmtl_constants_t* annmtl_get_constants() {{
    if (annmtl_constants_ptr == nullptr) {{
        annmtl_constants_ptr = static_cast<annmtl_constants_t*>(annmtl_malloc(sizeof(annmtl_constants_t)));
        std::memset(annmtl_constants_ptr, 0, sizeof(annmtl_constants_t));
    }}
    return annmtl_constants_ptr;
}}
"""
    for name, ctype in constants:
        host += f"""void set_{name}({ctype} value) {{
    {host_field_type(ctype)} tmp = value;
    annmtl_memcpy(&(annmtl_get_constants()->{name}), &tmp, sizeof(tmp));
}}
"""
    return msl, host


def translate(device_code, host_code, constants=[]):
    """
    Translate the device code (kernels and device functions) into MSL and the
    kernel launches in the host code into calls of the Metal runtime.

    constants is a list of (name, type) of the global constants.

    Returns: (msl_code, launcher_code, host_code)
    """
    items = parse_device_code(device_code)
    kernels = {item.name: item for item in items if isinstance(item, Kernel)}

    collect_instantiations(host_code, kernels)
    host_code, used = translate_launches(host_code, kernels)

    msl_constants, host_constants = constants_code(constants)

    msl_code = msl_constants
    for item in items:
        if isinstance(item, Kernel):
            msl_code += translate_kernel(item, constants)
        else:
            if "__constant__" in item:
                raise MetalTranslationError("unexpected __constant__ declaration in the device code")
            msl_code += item

    launchers = host_constants
    for name, value in sorted(used, key=lambda x: (x[0], x[1] or "")):
        launchers += generate_launcher(kernels[name], value, constants) + "\n"

    return msl_code, launchers, host_code


def to_cpp_raw_string(name, text):
    """
    Embed the shader source into the C++ code. Raw string literals are split in
    chunks, as some compilers limit the length of a single literal.
    """
    delimiter = "ANNMTL"
    while (")" + delimiter + '"') in text:
        delimiter += "_"
    chunk_size = 16000
    chunks = [text[i : i + chunk_size] for i in range(0, len(text), chunk_size)] or [""]
    literal = "\n".join(f'R"{delimiter}({chunk}){delimiter}"' for chunk in chunks)
    return f"static const char* {name} =\n{literal};\n"
